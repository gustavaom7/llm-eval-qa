"""Expand datasets/redteam_seeds.yaml into datasets/redteam.yaml with deepteam's deterministic transforms.

pip install -e ".[redteam]"
DEEPTEAM_TELEMETRY_OPT_OUT=YES python scripts/build_redteam.py
"""

from __future__ import annotations

import os
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def _techniques() -> dict:
    os.environ.setdefault("DEEPTEAM_TELEMETRY_OPT_OUT", "YES")
    os.environ.setdefault("DEEPEVAL_TELEMETRY_OPT_OUT", "YES")
    from deepteam.attacks.single_turn import (
        ROT13,
        Base64,
        ContextFlooding,
        EmbeddedInstructionJSON,
        Leetspeak,
    )

    # Only transforms that need no model: the same seed always gives the same attack.
    return {
        "base64": Base64,
        "context_flooding": ContextFlooding,
        "embedded_instruction_json": EmbeddedInstructionJSON,
        "leetspeak": Leetspeak,
        "rot13": ROT13,
    }


def build(seeds_path: Path, out_path: Path) -> None:
    techniques = _techniques()
    seeds = yaml.safe_load(Path(seeds_path).read_text(encoding="utf-8"))
    rows = []
    for seed in sorted(seeds, key=lambda s: s["id"]):
        base = {"seed": seed["id"], "vulnerability": seed["vulnerability"]}
        rows.append({"id": seed["id"], **base, "technique": "plain", "text": seed["text"]})
        for name in sorted(seed.get("variants", [])):
            text = techniques[name]().enhance(seed["text"])
            rows.append({"id": f"{seed['id']}--{name}", **base, "technique": name, "text": text})
    header = (
        "# Generated by scripts/build_redteam.py from datasets/redteam_seeds.yaml. Do not edit by hand.\n"
    )
    out_path.write_text(
        header + yaml.safe_dump(rows, sort_keys=False, allow_unicode=True, width=1000), encoding="utf-8"
    )


if __name__ == "__main__":
    build(ROOT / "datasets" / "redteam_seeds.yaml", ROOT / "datasets" / "redteam.yaml")
